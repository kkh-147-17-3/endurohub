// Build script: projects the South Korea province + municipality GeoJSON
// into flat, runtime-dependency-free TypeScript data modules for the
// calendar map view.
//
// Run manually whenever a source GeoJSON changes:
//   npm install   (d3-geo is a devDependency)
//   npm run build:geo
//
// Geographic boundary data derived from southkorea/southkorea-maps
// (https://github.com/southkorea/southkorea-maps), MIT License.
// Simplified with mapshaper. Projected with d3-geo geoMercator (ISC License).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { geoMercator, geoPath } from 'd3-geo';

const __dirname = dirname(fileURLToPath(import.meta.url));

// Shared contract with the map component — keep in sync with KOREA_VIEWBOX.
const VIEWBOX_W = 800;
const VIEWBOX_H = 780;
const PADDING = 24;

// Both layers come from ONE source so their shared borders match exactly:
// the municipalities GeoJSON is pre-processed with mapshaper (simplified,
// then 일반구 like 수원시장안구 dissolved into their parent 시 — every
// feature is one 기초자치단체), and the provinces GeoJSON is produced by
// dissolving those municipalities by province code. A province outline is
// therefore the exact union of its municipality outlines.
const MUNI_INPUT = join(__dirname, 'data', 'korea-municipalities.raw.geojson');
const PROV_INPUT = join(__dirname, 'data', 'korea-provinces.raw.geojson');
const PROV_OUTPUT = join(__dirname, '..', 'src', 'lib', 'geo', 'korea-provinces.ts');
const MUNI_OUTPUT = join(__dirname, '..', 'src', 'lib', 'geo', 'korea-municipalities.ts');

// Reference point used to verify the runtime closed-form projection.
const REF_NAME = '서울시청';
const REF_LNG = 126.9784;
const REF_LAT = 37.5667;

// Statistics Korea 2-digit area code -> app region code + full name.
// Municipalities carry a 5-digit code (first 2 digits = province); the
// province GeoJSON carries the 2-digit code in its `prov` property.
const REGION_BY_CODE2 = {
	11: { code: '서울', name: '서울특별시' },
	21: { code: '부산', name: '부산광역시' },
	22: { code: '대구', name: '대구광역시' },
	23: { code: '인천', name: '인천광역시' },
	24: { code: '광주', name: '광주광역시' },
	25: { code: '대전', name: '대전광역시' },
	26: { code: '울산', name: '울산광역시' },
	29: { code: '세종', name: '세종특별자치시' },
	31: { code: '경기', name: '경기도' },
	32: { code: '강원', name: '강원특별자치도' },
	33: { code: '충북', name: '충청북도' },
	34: { code: '충남', name: '충청남도' },
	35: { code: '전북', name: '전북특별자치도' },
	36: { code: '전남', name: '전라남도' },
	37: { code: '경북', name: '경상북도' },
	38: { code: '경남', name: '경상남도' },
	39: { code: '제주', name: '제주특별자치도' },
};

const r1 = (n) => Math.round(n * 10) / 10;
const roundPath = (d) => d.replace(/-?\d+\.?\d*/g, (m) => String(r1(parseFloat(m))));

// d3-geo uses spherical winding to decide a polygon's interior. The
// southkorea-maps source winds its rings the way d3 reads as "the whole
// globe minus the area" (geoArea ≈ 4π), which collapses fitExtent.
// Rewind in place so each exterior ring encloses a small area.
// `shoelace() >= 0` is the orientation d3 treats as the polygon interior
// (verified empirically: reversing a 4π ring yields its true ~0 area).
function shoelaceNonNegative(ring) {
	let area = 0;
	for (let i = 0, len = ring.length, j = len - 1; i < len; j = i++) {
		area += (ring[i][0] - ring[j][0]) * (ring[j][1] + ring[i][1]);
	}
	return area >= 0;
}
function rewindRings(rings) {
	rings.forEach((ring, i) => {
		// exterior ring (i === 0) → interior orientation; holes → opposite
		const wantNonNegative = i === 0;
		if (shoelaceNonNegative(ring) !== wantNonNegative) ring.reverse();
	});
}
function rewindGeometry(geometry) {
	if (geometry.type === 'Polygon') {
		rewindRings(geometry.coordinates);
	} else if (geometry.type === 'MultiPolygon') {
		geometry.coordinates.forEach(rewindRings);
	}
}

function loadGeoJSON(path) {
	const geo = JSON.parse(readFileSync(path, 'utf8'));
	if (geo.type !== 'FeatureCollection' || !Array.isArray(geo.features)) {
		throw new Error(`Not a GeoJSON FeatureCollection: ${path}`);
	}
	for (const feature of geo.features) rewindGeometry(feature.geometry);
	return geo;
}

const HEADER = [
	'// AUTO-GENERATED by scripts/build-korea-geo.mjs — DO NOT EDIT.',
	'//',
	'// Geographic boundary data derived from southkorea/southkorea-maps',
	'// (https://github.com/southkorea/southkorea-maps), MIT License.',
	'// Simplified with mapshaper. Projected with d3-geo geoMercator (ISC License).',
];

function buildProvinces(geo, projection, path) {
	const provinces = [];
	const seen = new Set();
	for (const feature of geo.features) {
		const prov = String(feature.properties?.prov ?? '');
		const region = REGION_BY_CODE2[prov];
		if (!region) throw new Error(`Unmapped province code: "${prov}"`);
		const { code, name } = region;
		if (seen.has(code)) throw new Error(`Duplicate region code: "${code}"`);
		seen.add(code);

		const [[x0, y0], [x1, y1]] = path.bounds(feature);
		const [cx, cy] = path.centroid(feature);
		provinces.push({
			code,
			name,
			d: roundPath(path(feature)),
			centroid: [r1(cx), r1(cy)],
			bbox: [
				[r1(x0), r1(y0)],
				[r1(x1), r1(y1)],
			],
		});
	}
	if (provinces.length !== 17) {
		throw new Error(`Expected 17 provinces, got ${provinces.length}`);
	}

	const scale = projection.scale();
	const [tx, ty] = projection.translate();
	const [refX, refY] = projection([REF_LNG, REF_LAT]);

	const lines = [...HEADER];
	lines.push('//');
	lines.push(
		`// Projection self-check: ${REF_NAME} [${REF_LNG}, ${REF_LAT}] ` +
			`-> [${r1(refX)}, ${r1(refY)}] in the ${VIEWBOX_W}x${VIEWBOX_H} viewBox.`,
	);
	lines.push('// projectLngLat() in ./project.ts must reproduce this within <0.5px.');
	lines.push('');
	lines.push('export interface KoreaProvince {');
	lines.push('\t/** App region code, e.g. "서울" "경기" … "제주". */');
	lines.push('\tcode: string;');
	lines.push('\t/** Original GeoJSON province name, e.g. "서울특별시". */');
	lines.push('\tname: string;');
	lines.push('\t/** Projected SVG path, in the 800x780 viewBox. */');
	lines.push('\td: string;');
	lines.push('\t/** Projected polygon centroid [x, y]. */');
	lines.push('\tcentroid: [number, number];');
	lines.push('\t/** Projected bounding box [[x0, y0], [x1, y1]]. */');
	lines.push('\tbbox: [[number, number], [number, number]];');
	lines.push('}');
	lines.push('');
	lines.push('/** Fixed SVG viewBox the province paths are projected into. */');
	lines.push(`export const KOREA_VIEWBOX = { w: ${VIEWBOX_W}, h: ${VIEWBOX_H} } as const;`);
	lines.push('');
	lines.push('/**');
	lines.push(' * d3.geoMercator() constants resolved by fitExtent() at build time.');
	lines.push(' * Consumed by projectLngLat() in ./project.ts to place race pins.');
	lines.push(' */');
	lines.push('export const KOREA_PROJECTION = {');
	lines.push(`\tscale: ${scale},`);
	lines.push(`\ttranslate: [${tx}, ${ty}] as [number, number],`);
	lines.push('} as const;');
	lines.push('');
	lines.push('export const KOREA_PROVINCES: KoreaProvince[] = [');
	for (const p of provinces) {
		lines.push('\t{');
		lines.push(`\t\tcode: ${JSON.stringify(p.code)},`);
		lines.push(`\t\tname: ${JSON.stringify(p.name)},`);
		lines.push(`\t\td: ${JSON.stringify(p.d)},`);
		lines.push(`\t\tcentroid: [${p.centroid[0]}, ${p.centroid[1]}],`);
		lines.push(
			`\t\tbbox: [[${p.bbox[0][0]}, ${p.bbox[0][1]}], [${p.bbox[1][0]}, ${p.bbox[1][1]}]],`,
		);
		lines.push('\t},');
	}
	lines.push('];');
	lines.push('');

	writeFileSync(PROV_OUTPUT, lines.join('\n'), 'utf8');
	return { count: provinces.length, refX: r1(refX), refY: r1(refY) };
}

function buildMunicipalities(geo, path) {
	// Group municipalities by their parent province (code prefix).
	const groups = {};
	let unmapped = 0;
	for (const feature of geo.features) {
		const code = String(feature.properties?.code ?? '');
		const region = REGION_BY_CODE2[code.slice(0, 2)]?.code;
		if (!region) {
			unmapped++;
			continue;
		}
		const [cx, cy] = path.centroid(feature);
		(groups[region] ??= []).push({
			name: feature.properties?.name ?? '',
			d: roundPath(path(feature)),
			centroid: [r1(cx), r1(cy)],
		});
	}
	if (unmapped > 0) {
		throw new Error(`${unmapped} municipalities had an unmapped area code`);
	}

	const lines = [...HEADER];
	lines.push('//');
	lines.push('// 시·군·구 polygons, projected with the same geoMercator as the');
	lines.push('// provinces so they overlay exactly. Grouped by province code.');
	lines.push('');
	lines.push('export interface KoreaMunicipality {');
	lines.push('\t/** 시·군·구 name, e.g. "종로구". */');
	lines.push('\tname: string;');
	lines.push('\t/** Projected SVG path, in the 800x780 viewBox. */');
	lines.push('\td: string;');
	lines.push('\t/** Projected polygon centroid [x, y], for label placement. */');
	lines.push('\tcentroid: [number, number];');
	lines.push('}');
	lines.push('');
	lines.push('/** 시·군·구 polygons keyed by province code (서울, 경기, … 제주). */');
	lines.push('export const KOREA_MUNICIPALITIES: Record<string, KoreaMunicipality[]> = {');
	let total = 0;
	for (const region of Object.values(REGION_BY_CODE2).map((r) => r.code)) {
		const list = groups[region] ?? [];
		total += list.length;
		lines.push(`\t${JSON.stringify(region)}: [`);
		for (const m of list) {
			lines.push(
				`\t\t{ name: ${JSON.stringify(m.name)}, ` +
					`centroid: [${m.centroid[0]}, ${m.centroid[1]}], ` +
					`d: ${JSON.stringify(m.d)} },`,
			);
		}
		lines.push('\t],');
	}
	lines.push('};');
	lines.push('');

	writeFileSync(MUNI_OUTPUT, lines.join('\n'), 'utf8');
	return { total };
}

function main() {
	const provGeo = loadGeoJSON(PROV_INPUT);

	// One projection, fitted to the whole country, shared by both layers.
	const projection = geoMercator().fitExtent(
		[
			[PADDING, PADDING],
			[VIEWBOX_W - PADDING, VIEWBOX_H - PADDING],
		],
		provGeo,
	);
	const path = geoPath(projection);

	const prov = buildProvinces(provGeo, projection, path);
	console.log(`✓ ${PROV_OUTPUT}`);
	console.log(`  ${prov.count} provinces · ${REF_NAME} -> [${prov.refX}, ${prov.refY}]`);

	const muniGeo = loadGeoJSON(MUNI_INPUT);
	const muni = buildMunicipalities(muniGeo, path);
	console.log(`✓ ${MUNI_OUTPUT}`);
	console.log(`  ${muni.total} municipalities`);
}

main();
